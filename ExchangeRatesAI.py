import csv
from decimal import Decimal, ROUND_HALF_UP
from pathlib import Path

#Name of the CSV file and the column holding the USD/CAD rate. 
DEFAULT_CSV_FILE = "BankOfCanadaExchangeRate.2026.csv"
USD_CAD_COLUMN = "FXAUSDCAD"
#Currencies supported by the converter.
SUPPORTED_CURRENCIES = ("USD", "CAD")
#Rounding precision: nearest penny.
PENNY = Decimal("0.01")

class ExchangeRates: #Reads a Bank of Canada exchange rate file and converts between USD and CAD.

    def __init__(self, filename):
        """
        Initialize the converter by reading the exchange rate file.
        Parameters
        filename : str or Path
            Path to the Bank of Canada exchange rate CSV file.
        """
        self.filename = Path(filename)
        self.rate_date = None   # Date of the rate that was read (e.g. "2025-01-01")
        self.usd_cad = None     # CAD per 1 USD, stored as a Decimal
        self._load_rate()

    # Private helper method to read the CSV, find and store the most recent USD/CAD rate.
    def _load_rate(self):

        """The file is read with 'utf-8-sig' because the Bank of Canada file starts with a byte-order mark (BOM) 
        that would otherwise corrupt the first column name. Rows are scanned from the bottom so the 
        latest row that actually contains a USD/CAD value is used."""

        with open(self.filename, newline="", encoding="utf-8-sig") as file:
            rows = list(csv.DictReader(file))

        for row in reversed(rows):
            value = (row.get(USD_CAD_COLUMN) or "").strip()
            if value:
                self.usd_cad = Decimal(value)
                self.rate_date = row["Date"].strip()
                return

        raise ValueError(
            f"No USD/CAD rate found in column '{USD_CAD_COLUMN}' of {self.filename}"
        )

    #Public methods
    
    def get_rate(self):
        """Return the USD/CAD exchange rate (CAD per 1 USD) as a Decimal."""
        return self.usd_cad

    def convert(self, amount, from_currency, to_currency):
        """
        Convert an amount between USD and CAD using the rate from the file.
        Parameters
        amount : float, int, str or Decimal
            Amount of money to convert.
        from_currency : str
            Currency of the amount: "USD" or "CAD" (case-insensitive).
        to_currency : str
            Currency to convert into: "USD" or "CAD" (case-insensitive).
        Returns
        Decimal
            The converted amount, rounded to the nearest penny.
        """

        amount = Decimal(str(amount))
        from_currency = from_currency.strip().upper()
        to_currency = to_currency.strip().upper()

        if from_currency == to_currency:
            result = amount
        elif from_currency == "USD" and to_currency == "CAD":
            result = amount * self.usd_cad
        elif from_currency == "CAD" and to_currency == "USD":
            result = amount / self.usd_cad
        else:
            raise ValueError("Currencies must be either USD or CAD.")

        return result.quantize(PENNY, rounding=ROUND_HALF_UP)

def format_money(amount, currency):
    return f"${amount:,.2f} {currency.upper()}"

def get_user_input():
    """
    Prompt the user for the amount and the 'from' and 'to' currencies.
    Input is assumed to be valid (no validation checks are required).
    Returns
    tuple
        (amount as Decimal, from currency, to currency)
    """
    amount_text = input("Enter the amount to convert: ")
    amount = Decimal(amount_text.replace("$", "").replace(",", "").strip())
    from_currency = input("Convert from (USD or CAD): ").strip().upper()
    to_currency = input("Convert to (USD or CAD): ").strip().upper()
    return amount, from_currency, to_currency

def main(): 
    """Run the exchange rate calculator."""
    # Look for the CSV next to this script first, then in the current folder.
    csv_path = Path(__file__).resolve().parent / DEFAULT_CSV_FILE
    if not csv_path.exists():
        csv_path = Path(DEFAULT_CSV_FILE)

    rates = ExchangeRates(csv_path)
    print(f"Latest USD/CAD exchange rate ({rates.rate_date}): {rates.get_rate()}")
    print("(1 USD = {} CAD)\n".format(rates.get_rate()))

    amount, from_currency, to_currency = get_user_input()
    converted = rates.convert(amount, from_currency, to_currency)

    print()
    print(
        f"{format_money(amount.quantize(PENNY, rounding=ROUND_HALF_UP), from_currency)}"
        f" = {format_money(converted, to_currency)}"
    )

if __name__ == "__main__":
    main()
